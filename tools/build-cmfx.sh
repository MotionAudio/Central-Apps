#!/bin/bash
# Central FX (10.2): builds the plugin core (central-usage/native/cmfx/) to WebAssembly and writes the browser runtime
# production/cmfx/cmfx.js (from cmfx.src.js, with the WebAssembly inside), then copies it to every app that plays
# Central FX plugins in a browser engine:
#   central-usage/app/cmfx.js          Central Usage / Central Control (Studio, the effects)
#   js/cmfx.js                         the Central Pedal's app (pads, the buses, tracks)
#   server/public/production/cmfx/cmfx.js   the website's Central Production (and Central Production's app, from it)
# and copies the builder (plugin-builder.js / .css, presets.js) to server/public/production/plugin-builder/.
# Run it after changing anything in central-usage/native/cmfx/ or production/cmfx/cmfx.src.js, and commit the results.
# cmfx.js carries a hash of the C it was built from; test-cmfx.mjs fails when they no longer match.
#   tools/build-cmfx.sh            build + copy
#   tools/build-cmfx.sh --wasm F   only build the WebAssembly to F (the tests)
# Needs clang with the wasm32 target and wasm-ld (Ubuntu: clang lld). No emscripten.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/central-usage/native/cmfx"
CLANG="${CLANG:-$(command -v clang-18 || command -v clang)}"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
WASM="$TMP/cmfx.wasm"
[ "${1:-}" = "--wasm" ] && WASM="$2"
"$CLANG" --target=wasm32 -O2 -nostdlib -ffreestanding -ffp-contract=off -Wall -Wno-misleading-indentation \
  -Wl,--no-entry -Wl,-z,stack-size=1048576 -Wl,--strip-all \
  -o "$WASM" "$SRC/cmfx_wasm.c" "$SRC/cmfx.c" "$SRC/cmfx_code.c" "$SRC/cmfx_util.c"
[ "${1:-}" = "--wasm" ] && exit 0
python3 - "$ROOT" "$WASM" <<'EOF'
import base64, hashlib, os, sys
root, wasm = sys.argv[1], sys.argv[2]
src = os.path.join(root, "central-usage", "native", "cmfx")
h = hashlib.sha256()
for f in ("cmfx.h", "cmfx_int.h", "cmfx.c", "cmfx_code.c", "cmfx_util.c", "cmfx_wasm.c"):
    h.update(open(os.path.join(src, f), "rb").read())
tpl = open(os.path.join(root, "production", "cmfx", "cmfx.src.js"), encoding="utf-8").read()
data = base64.b64encode(open(wasm, "rb").read()).decode()
assert '"@WASM@"' in tpl
out = tpl.replace('"@WASM@"', '"' + data + '"', 1)
out = out.replace("version: 1 };", "version: 1, source: \"" + h.hexdigest() + "\" };", 1)
head = "/* GENERATED by tools/build-cmfx.sh from production/cmfx/cmfx.src.js and central-usage/native/cmfx/ - don't edit. */\n"
for dest in ("production/cmfx/cmfx.js", "central-usage/app/cmfx.js", "js/cmfx.js", "server/public/production/cmfx/cmfx.js"):
    p = os.path.join(root, dest); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", encoding="utf-8").write(head + out)
print("cmfx.js: %d KB of WebAssembly, source %s" % (len(data) * 3 // 4 // 1024, h.hexdigest()[:12]))
# the builder's examples, as one script (so they work without fetching files)
import json
pd = os.path.join(root, "production", "plugin-builder", "presets")
items = [json.load(open(os.path.join(pd, f), encoding="utf-8")) for f in sorted(os.listdir(pd)) if f.endswith(".cmfx.json")]
open(os.path.join(root, "production", "plugin-builder", "presets.js"), "w", encoding="utf-8").write(
    "/* GENERATED by tools/build-cmfx.sh from production/plugin-builder/presets/*.cmfx.json - don't edit. */\nwindow.CPPluginPresets = " + json.dumps(items, indent=1, ensure_ascii=False) + ";\n")
print("presets.js: %d examples" % len(items))
import shutil
for f in ("plugin-builder.js", "plugin-builder.css", "presets.js"):
    shutil.copy(os.path.join(root, "production", "plugin-builder", f), os.path.join(root, "server", "public", "production", "plugin-builder", f))
shutil.copy(os.path.join(root, "production", "plugin-builder", "presets.js"), os.path.join(root, "js", "cmfx-presets.js"))   # the pedal app and Central Usage (the examples in their pickers)
EOF
